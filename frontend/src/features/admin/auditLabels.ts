export const auditResults: Record<string, string> = {
  SUCCESS: 'Correcto',
  FAILURE: 'Fallido',
}

const searchCodesByLabel = new Map(
  [...Object.entries(auditOperations), ...Object.entries(auditResults)].map(([code, label]) => [label.toLowerCase(), code]),
)

export function auditSearchTerm(search: string) {
  const term = search.trim()
  return searchCodesByLabel.get(term.toLowerCase()) ?? term
}
